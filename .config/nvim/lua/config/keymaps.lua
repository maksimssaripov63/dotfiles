-- ==========================================================================

-- 1. Удаление текущей вкладки (буфера) без закрытия самого Neovim
vim.keymap.set("n", "<leader>q", "<cmd>Snacks.bufdelete()<CR>", { desc = "Закрыть текущую вкладку" })

-- 2. ВОЗВРАЩАЕМ ВСТРОЕННЫЙ ТЕРМИНАЛ
-- Теперь при нажатии Пробел + f + t снизу гарантированно откроется консоль!
vim.keymap.set("n", "<leader>ft", function() Snacks.terminal.toggle() end, { desc = "Открыть встроенный терминал" })

-- 3. КНОПКА КОМПИЛЯЦИИ И ПРОШИВКИ ПЛАТЫ DUNAJ В ОДИН КЛИК
-- Нажмите Пробел + p + u, и Neovim сам соберет код и зальет программу по USB
vim.keymap.set("n", "<leader>pu", function()
  Snacks.terminal.open("pio run --target upload")
end, { desc = "Прошить плату Dunaj 5.2" })
